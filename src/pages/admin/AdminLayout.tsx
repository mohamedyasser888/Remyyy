export function AdminLayout() {
  const { logout } = useAdminAuth();
  const navigate   = useNavigate();
  const [unread, setUnread] = useState(0);

  useEffect(() => {
    const check = async () => setUnread(await getUnreadCount());
    check();
  }, []);
  useRealtimeSync(['messages'], async () => setUnread(await getUnreadCount()), { admin: true });

  const handleLogout = () => {
    logout();
    navigate(ROUTES.ADMIN, { replace: true });
  };

  return (
    <div className="flex h-screen bg-slate-50">
      {/* Sidebar */}
      <aside className="w-64 bg-slate-900 text-white flex flex-col">
        <div className="p-6 border-b border-slate-700">
          <div>
            <img src="/remy-transparent.png" alt="Remy" className="w-36 h-auto object-contain object-left" />
            <p className="text-xs text-slate-400 mt-1">Admin Panel</p>
          </div>
        </div>

        <nav className="flex-1 px-3 py-4 space-y-1">
          {navItems.map(item => (
            <NavLink
              key={item.to}
              to={item.to}
              className={({ isActive }) =>
                `flex items-center gap-3 px-4 py-3 rounded-lg transition-all text-sm relative ${
                  isActive
                    ? 'bg-primary-500 text-white font-medium'
                    : 'text-slate-300 hover:bg-slate-800'
                }`
              }
            >
              {item.icon}
              <span>{item.label}</span>
              {item.to === ROUTES.ADMIN_MESSAGES && unread > 0 && (
                <span className="absolute right-3 top-1/2 -translate-y-1/2 bg-rose-500 text-white text-xs font-bold min-w-[18px] h-[18px] rounded-full flex items-center justify-center px-1">
                  {unread > 99 ? '99+' : unread}
                </span>
              )}
            </NavLink>
          ))}
        </nav>

        <div className="p-4 border-t border-slate-700">
          <button
            onClick={handleLogout}
            className="flex items-center gap-3 px-4 py-3 w-full rounded-lg text-slate-300 hover:bg-slate-800 text-sm transition-all"
          >
            <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
            </svg>
            <span>Logout</span>
          </button>
        </div>
      </aside>

      {/* Content */}
      <main className="flex-1 overflow-y-auto">
        <Outlet />
      </main>
    </div>
  );
}
